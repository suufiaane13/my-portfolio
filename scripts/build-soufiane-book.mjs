#!/usr/bin/env node
/**
 * Parse SuuFiaane13 PGN → generate src/lib/chess/soufianeBook.generated.ts
 *
 * Run:  node scripts/build-soufiane-book.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Chess } from 'chess.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const PGN_PATH = join(ROOT, 'SuuFiaane13_1000-1100.pgn')
const OUT_PATH = join(ROOT, 'src', 'lib', 'chess', 'soufianeBook.generated.ts')

const pgnText = readFileSync(PGN_PATH, 'utf-8')

// ── Split PGN into individual games ──────────────────────────────────────────
const games = []
let current = ''
for (const line of pgnText.split('\n')) {
  if (line.startsWith('[Event ') && current.trim()) {
    games.push(current)
    current = ''
  }
  current += line + '\n'
}
if (current.trim()) games.push(current)

console.log(`Found ${games.length} games in PGN`)

// ── Parse each game and extract FEN → move entries ──────────────────────────
// Map<FEN, Map<UCI_move, count>>
const book = new Map()
const MAX_PLY = 30 // only use first 30 plies (15 moves each side)

let totalPositions = 0
let parsedGames = 0

for (const gameText of games) {
  const chess = new Chess()

  // Strip clock annotations {[%clk ...]} and commentary {...}
  const cleaned = gameText
    .replace(/\{[^}]*\}/g, '')
    .replace(/\$\d+/g, '') // NAG symbols like $1 $2
    .replace(/\s+/g, ' ')
    .trim()

  try {
    chess.loadPgn(cleaned)
  } catch {
    continue
  }

  const history = chess.history({ verbose: true })
  if (history.length < 4) continue // skip very short games

  parsedGames++
  const replay = new Chess()

  for (let i = 0; i < Math.min(history.length, MAX_PLY); i++) {
    const fen = replay.fen()
    const uci = `${history[i].from}${history[i].to}${history[i].promotion ?? ''}`

    if (!book.has(fen)) book.set(fen, new Map())
    const moves = book.get(fen)
    moves.set(uci, (moves.get(uci) ?? 0) + 1)
    totalPositions++

    replay.move(history[i].san)
  }
}

console.log(`Parsed ${parsedGames} games → ${book.size} unique positions, ${totalPositions} total entries`)

// ── Generate TypeScript ─────────────────────────────────────────────────────
const lines = [
  '// AUTO-GENERATED by scripts/build-soufiane-book.mjs — DO NOT EDIT',
  `// Source: SuuFiaane13_1000-1100.pgn (${parsedGames} games, ${book.size} positions)`,
  '',
  'export interface SoufianeBookEntry {',
  '  move: string',
  '  weight: number',
  '}',
  '',
  '/** FEN → weighted move replies extracted from Soufiane\'s real games. */',
  'export const SOUFIANE_BOOK: Record<string, SoufianeBookEntry[]> = {',
]

let entries = 0
for (const [fen, moves] of book) {
  // Escape FEN for TS string key (backticks not needed since FEN has no backticks)
  const safeFen = fen.replace(/\\/g, '\\\\')
  const moveArray = [...moves.entries()]
    .sort((a, b) => b[1] - a[1]) // sort by frequency descending
    .map(([move, count]) => `    { move: '${move}', weight: ${count} }`)

  lines.push(`  '${safeFen}': [`)
  lines.push(moveArray.join(',\n'))
  lines.push('  ],')
  entries += moveArray.length
}

lines.push('}')
lines.push('')
lines.push(`// ${entries} total move entries across ${book.size} positions`)
lines.push('')

writeFileSync(OUT_PATH, lines.join('\n'))
console.log(`Wrote ${OUT_PATH} (${entries} entries)`)
